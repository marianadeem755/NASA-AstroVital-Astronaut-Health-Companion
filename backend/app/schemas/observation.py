from datetime import UTC, datetime, timedelta
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

# Metrics that count toward the completeness / quality score.
METRIC_FIELDS = [
    "heart_rate_bpm", "sleep_hours", "fatigue_level", "stress_level", "mood_score",
    "spo2_percent", "body_temperature_c", "systolic_bp", "diastolic_bp",
]


def to_utc(value: datetime) -> datetime:
    """Naive datetimes are assumed to already be UTC; aware ones are converted."""
    if value.tzinfo is None:
        return value.replace(tzinfo=UTC)
    return value.astimezone(UTC)


class ObservationCreate(BaseModel):
    astronaut_id: int = Field(gt=0)
    observed_at: datetime
    heart_rate_bpm: float | None = Field(default=None, ge=20, le=300)
    sleep_hours: float | None = Field(default=None, ge=0, le=24)
    fatigue_level: int | None = Field(default=None, ge=0, le=10)
    stress_level: int | None = Field(default=None, ge=0, le=10)
    mood_score: int | None = Field(default=None, ge=0, le=10)
    spo2_percent: float | None = Field(default=None, ge=50, le=100)
    body_temperature_c: float | None = Field(default=None, ge=25, le=45)
    systolic_bp: float | None = Field(default=None, ge=40, le=300)
    diastolic_bp: float | None = Field(default=None, ge=20, le=200)
    extra_metrics: dict | None = None
    # Idempotency key generated by the offline client (e.g. crypto.randomUUID()).
    client_uuid: str | None = Field(default=None, min_length=8, max_length=64)

    @field_validator("observed_at")
    @classmethod
    def _utc(cls, v: datetime) -> datetime:
        v = to_utc(v)
        if v > datetime.now(UTC).replace(microsecond=0) + timedelta(minutes=5):
            raise ValueError("observed_at cannot be in the future")
        return v

    @model_validator(mode="after")
    def _at_least_one_metric(self):
        if all(getattr(self, f) is None for f in METRIC_FIELDS) and not self.extra_metrics:
            raise ValueError("at least one metric must be provided")
        return self


class ObservationRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    astronaut_id: int
    observed_at: datetime
    heart_rate_bpm: float | None
    sleep_hours: float | None
    fatigue_level: int | None
    stress_level: int | None
    mood_score: int | None
    spo2_percent: float | None
    body_temperature_c: float | None
    systolic_bp: float | None
    diastolic_bp: float | None
    extra_metrics: dict | None
    client_uuid: str | None
    missing_fields: list[str] | None
    quality_score: float | None
    created_at: datetime


class ObservationPage(BaseModel):
    items: list[ObservationRead]
    total: int
    skip: int
    limit: int


class BulkObservationRequest(BaseModel):
    observations: list[ObservationCreate] = Field(min_length=1, max_length=500)


class BulkItemResult(BaseModel):
    index: int
    status: Literal["created", "duplicate", "rejected"]
    observation_id: int | None = None
    detail: str | None = None


class BulkObservationResponse(BaseModel):
    created: int
    duplicates: int
    rejected: int
    results: list[BulkItemResult]
